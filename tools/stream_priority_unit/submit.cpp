#include <acl/acl_rt.h>
#include <cstdint>

// One host call enqueues the short train, one hardware task per iteration.
extern "C" __attribute__((visibility("default"))) aclError stream_priority_submit(aclrtFuncHandle kernel,
                                                                                  uint32_t blocks, aclrtStream stream,
                                                                                  uint64_t* stamps, uint32_t tasks,
                                                                                  uint64_t hold_ticks) {
  aclrtLaunchKernelAttr attr{};
  attr.id = ACL_RT_LAUNCH_KERNEL_ATTR_SCHEM_MODE;
  attr.value.schemMode = 1;  // Admit a task only when all requested cores are available.
  aclrtLaunchKernelCfg cfg{&attr, 1};
  for (uint32_t task = 0; task < tasks; ++task) {
    struct {
      uint64_t* stamps;
      uint64_t hold_ticks;
      void* overflow_status;  // Trailing argument generated by the Ascend C kernel wrapper, unused in Release.
    } args{stamps + static_cast<uint64_t>(task) * blocks * 8, hold_ticks, nullptr};
    const auto rc = aclrtLaunchKernelWithHostArgs(kernel, blocks, stream, &cfg, &args, sizeof(args), nullptr, 0);
    if (rc != ACL_SUCCESS) {
      return rc;
    }
  }
  return ACL_SUCCESS;
}
